import type { GeneratedProject } from "../contracts/interfaces";
import type { FunctionSignature, TypedProgram } from "../contracts/outcome";
import { CORE_VERSION, COMPILER_VERSION } from "../contracts/version";
import {
  collectRecords,
  emitFunctionBody,
  functionBySignature,
  targetType,
  type Dialect,
  type RecordMap,
} from "./codegen";

export function emitGo(
  program: TypedProgram,
  entryName: string,
  options: { projectName?: string } = {},
): GeneratedProject {
  void options;
  const entry = program.functions.find((fn) => fn.name === entryName);
  if (!entry) throw new Error(`entry function "${entryName}" was not found`);
  const records = collectRecords(program);

  const dialect: Dialect = {
    target: "go",
    intType: "int32",
    intMinLiteral: "int32(-2147483648)",
    declare: (name, type, init) => [`var ${name} ${type} = ${init}`, `_ = ${name}`],
    declareRes: (name, init) => [`var ${name} Res = ${init}`, `_ = ${name}`],
    assign: (name, expr) => [`${name} = ${expr}`],
    ifOpen: (cond) => `if ${cond} {`,
    elseOpen: () => `} else {`,
    closeBlock: () => `}`,
    returnStmt: (expr) => `return ${expr}`,
    resFailed: (expr) => `!${expr}.ok`,
    resValue: (expr) => `${expr}.value`,
    resOk: (expr) => `ok(${expr})`,
    resFail: (code, node) => `fail(${code}, ${node})`,
    checked: (op, args, node) => `${op}(${[...args, String(node)].join(", ")})`,
    call: (fn, args) => `${fn}(${args.join(", ")})`,
    recordLiteral: (record, values) =>
      record.fields.length === 0
        ? `${record.targetName}{}`
        : `${record.targetName}{${record.fields
            .map((field, index) => `${field.targetName}: ${values[index]}`)
            .join(", ")}}`,
    fieldAccess: (target, record, index) => `${target}.${record.fields[index].targetName}`,
    fieldEquals: (left, right, record, index) =>
      `${left}.${record.fields[index].targetName} == ${right}.${record.fields[index].targetName}`,
  };

  const recordDeclarations = renderRecords(records, dialect);
  const functions = program.functions
    .map((signature) => renderFunction(program, signature, dialect, records))
    .join("\n\n");

  const main = renderMain(entry);
  const binaryName = process.platform === "win32" ? "hs_program.exe" : "hs_program";
  const needsStrconv = entry.params.some((param) => param.type === "i32");
  const imports = needsStrconv ? '\t"fmt"\n\t"os"\n\t"strconv"' : '\t"fmt"\n\t"os"';
  const source = `// Generated by h# ${COMPILER_VERSION} (core ${CORE_VERSION}). Do not edit.
package main

import (
${imports}
)

type Res struct {
	ok    bool
	value int32
	code  int
	node  int
}

func ok(value int32) Res {
	return Res{ok: true, value: value, code: 0, node: 0}
}

func fail(code int, node int) Res {
	return Res{ok: false, value: 0, code: code, node: node}
}

func add(a int32, b int32, node int) Res {
	r := int64(a) + int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func sub(a int32, b int32, node int) Res {
	r := int64(a) - int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func mul(a int32, b int32, node int) Res {
	r := int64(a) * int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func neg(a int32, node int) Res {
	r := -int64(a)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

${recordDeclarations}

${functions}

${main}
`;

  return {
    target: "go",
    files: [
      {
        path: "go.mod",
        content: `module hsprogram

go 1.22
`,
      },
      { path: "main.go", content: source },
    ],
    build: ["go", "build", "-o", `bin/${binaryName}`, "."],
    run: [`bin/${binaryName}`],
  };
}

function renderRecords(records: RecordMap, dialect: Dialect): string {
  return [...records.values()]
    .map((record) => {
      const lines = [`type ${record.targetName} struct {`];
      for (const field of record.fields) {
        lines.push(`\t${field.targetName} ${targetType(field.type, records, dialect.intType)}`);
      }
      lines.push("}");
      return lines.join("\n");
    })
    .join("\n\n");
}

function renderFunction(
  program: TypedProgram,
  signature: FunctionSignature,
  dialect: Dialect,
  records: RecordMap,
): string {
  const fn = functionBySignature(program, signature);
  const parameters = fn.params
    .map((param) => `${param.targetName} ${targetType(param.type.name, records, dialect.intType)}`)
    .join(", ");
  const body = emitFunctionBody(fn, dialect, records);
  return `func ${signature.targetName}(${parameters}) Res {\n${indent(body, 1)}\n}`;
}

function renderMain(entry: FunctionSignature): string {
  const params = entry.params;
  const lines: string[] = [];
  lines.push("func badArgs() {");
  lines.push('\tfmt.Println(`{"status":"badargs"}`)');
  lines.push("\tos.Exit(2)");
  lines.push("}");
  lines.push("");
  lines.push("func main() {");
  lines.push(`\tif len(os.Args)-1 != ${params.length} {`);
  lines.push("\t\tbadArgs()");
  lines.push("\t}");
  params.forEach((param, index) => {
    const name = `p${index}`;
    if (param.type === "i32") {
      lines.push(`\t${name}raw, err${index} := strconv.ParseInt(os.Args[${index + 1}], 10, 32)`);
      lines.push(`\tif err${index} != nil {`);
      lines.push("\t\tbadArgs()");
      lines.push("\t}");
      lines.push(`\t${name} := int32(${name}raw)`);
      lines.push(`\t_ = ${name}`);
    } else {
      lines.push(`\tvar ${name} int32`);
      lines.push(`\tswitch os.Args[${index + 1}] {`);
      lines.push('\tcase "true":');
      lines.push(`\t\t${name} = 1`);
      lines.push('\tcase "false":');
      lines.push(`\t\t${name} = 0`);
      lines.push("\tdefault:");
      lines.push("\t\tbadArgs()");
      lines.push("\t}");
    }
  });
  lines.push(
    `\tresult := ${entry.targetName}(${params.map((_, i) => `p${i}`).join(", ")})`,
  );
  lines.push("\tif result.ok {");
  if (entry.returnType === "bool") {
    lines.push('\t\ttext := "false"');
    lines.push("\t\tif result.value != 0 {");
    lines.push('\t\t\ttext = "true"');
    lines.push("\t\t}");
    lines.push(
      '\t\tfmt.Printf("{\\"status\\":\\"ok\\",\\"type\\":\\"bool\\",\\"value\\":%s}\\n", text)',
    );
  } else {
    lines.push(
      '\t\tfmt.Printf("{\\"status\\":\\"ok\\",\\"type\\":\\"i32\\",\\"value\\":%d}\\n", result.value)',
    );
  }
  lines.push("\t} else {");
  lines.push(
    '\t\tfmt.Printf("{\\"status\\":\\"error\\",\\"code\\":\\"E_OVERFLOW\\",\\"node\\":%d}\\n", result.node)',
  );
  lines.push("\t\tos.Exit(1)");
  lines.push("\t}");
  lines.push("}");
  return lines.join("\n");
}

function indent(text: string, tabs: number): string {
  const prefix = "\t".repeat(tabs);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}
