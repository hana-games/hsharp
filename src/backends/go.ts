import type { GeneratedProject } from "../contracts/interfaces";
import type { FunctionSignature, TypedProgram } from "../contracts/outcome";
import { INDEX_FAILURE_CODE } from "../contracts/outcome";
import { CORE_VERSION, COMPILER_VERSION } from "../contracts/version";
import {
  collectRecords,
  collectVariants,
  emitFunctionBody,
  functionBySignature,
  quoteString,
  targetType,
  type Dialect,
  type RecordMap,
  type VariantMap,
} from "./codegen";

export function emitGo(
  program: TypedProgram,
  entryName: string,
  options: { projectName?: string } = {},
): GeneratedProject {
  void options;
  const entry = program.functions.find((fn) => fn.name === entryName);
  if (!entry) throw new Error(`entry function "${entryName}" was not found`);
  const records = collectRecords(program);
  const variants = collectVariants(program);

  const dialect: Dialect = {
    target: "go",
    intType: "int32",
    stringType: "string",
    intMinLiteral: "int32(-2147483648)",
    declare: (name, type, init) => [`var ${name} ${type} = ${init}`, `_ = ${name}`],
    declareRes: (name, init) => [`var ${name} Res = ${init}`, `_ = ${name}`],
    assign: (name, expr) => [`${name} = ${expr}`],
    ifOpen: (cond) => `if ${cond} {`,
    elseIfOpen: (cond) => `} else if ${cond} {`,
    elseOpen: () => `} else {`,
    closeBlock: () => `}`,
    returnStmt: (expr) => `return ${expr}`,
    resFailed: (expr) => `!${expr}.ok`,
    resValue: (expr) => `${expr}.value`,
    resOk: (expr) => `ok(${expr})`,
    resOkRecord: (_record, expr) => `okRecord(${expr})`,
    resRecordValue: (expr, record) => `${expr}.payload.(${record.targetName})`,
    resOkVariant: (_variant, expr) => `okRecord(${expr})`,
    resVariantValue: (expr, variant) => `${expr}.payload.(${variant.targetName})`,
    resOkString: (expr) => `okString(${expr})`,
    resStringValue: (expr) => `${expr}.payload.(string)`,
    stringLiteral: quoteString,
    stringValue: (expr) => expr,
    emptyString: () => `""`,
    valueEquals: (left, right) => `${left} == ${right}`,
    resFail: (code, node) => `fail(${code}, ${node})`,
    checked: (op, args, node) => `${op}(${[...args, String(node)].join(", ")})`,
    call: (fn, args) => `${fn}(${args.join(", ")})`,
    recordLiteral: (record, values) =>
      record.fields.length === 0
        ? `${record.targetName}{}`
        : `${record.targetName}{${record.fields
            .map((field, index) => `${field.targetName}: ${values[index]}`)
            .join(", ")}}`,
    fieldAccess: (target, record, index) => `${target}.${record.fields[index].targetName}`,
    fieldEquals: (left, right, record, index) =>
      `${left}.${record.fields[index].targetName} == ${right}.${record.fields[index].targetName}`,
    constructVariant: (variant, alternative, values) => {
      const fields = ["tag", ...Array.from({ length: variant.maxArity }, (_unused, index) => `p${index + 1}`)];
      const assigned = [String(alternative.tag), ...values, ...Array(Math.max(0, variant.maxArity - values.length)).fill("0")];
      return `${variant.targetName}{${fields
        .map((field, index) => `${field}: ${assigned[index]}`)
        .join(", ")}}`;
    },
    variantTag: (expr) => `${expr}.tag`,
    variantPayload: (expr, _variant, index) => `${expr}.p${index + 1}`,
    variantEquals: (left, right, variant) =>
      variant.maxArity === 0
        ? `${left}.tag == ${right}.tag`
        : `(${left}.tag == ${right}.tag && ${Array.from(
            { length: variant.maxArity },
            (_unused, index) => `${left}.p${index + 1} == ${right}.p${index + 1}`,
          ).join(" && ")})`,
    listType: (element) => `[]${element}`,
    listLiteral: (values) => `[]int32{${values.join(", ")}}`,
    emptyList: () => `[]int32{}`,
    listValue: (expr) => expr,
    listLength: (expr) => `int32(len(${expr}))`,
    listIndex: (list, index, node) => `index(${list}, ${index}, ${node})`,
    listEquals: (left, right) => `listEquals(${left}, ${right})`,
    resOkList: (expr) => `okRecord(${expr})`,
    resListValue: (expr) => `${expr}.payload.([]int32)`,
  };

  const recordDeclarations = renderRecords(records, dialect, variants);
  const variantDeclarations = renderVariants(variants, dialect);
  const functions = program.functions
    .map((signature) => renderFunction(program, signature, dialect, records, variants))
    .join("\n\n");

  const main = renderMain(entry);
  const binaryName = process.platform === "win32" ? "hs_program.exe" : "hs_program";
  const needsStrconv = entry.params.some((param) => param.type === "i32");
  const imports = needsStrconv ? '\t"fmt"\n\t"os"\n\t"strconv"' : '\t"fmt"\n\t"os"';
  const source = `// Generated by h# ${COMPILER_VERSION} (core ${CORE_VERSION}). Do not edit.
package main

import (
${imports}
)

type Res struct {
	ok      bool
	value   int32
	payload any
	code    int
	node    int
}

func ok(value int32) Res {
	return Res{ok: true, value: value, code: 0, node: 0}
}

func okRecord(payload any) Res {
	return Res{ok: true, value: 0, payload: payload, code: 0, node: 0}
}

func okString(value string) Res {
	return Res{ok: true, value: 0, payload: value, code: 0, node: 0}
}

func fail(code int, node int) Res {
	return Res{ok: false, value: 0, code: code, node: node}
}

func add(a int32, b int32, node int) Res {
	r := int64(a) + int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func sub(a int32, b int32, node int) Res {
	r := int64(a) - int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func mul(a int32, b int32, node int) Res {
	r := int64(a) * int64(b)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func neg(a int32, node int) Res {
	r := -int64(a)
	if r < -2147483648 || r > 2147483647 {
		return fail(1, node)
	}
	return ok(int32(r))
}

func index(list []int32, index int32, node int) Res {
	if index < 0 || int(index) >= len(list) {
		return fail(${INDEX_FAILURE_CODE}, node)
	}
	return ok(list[index])
}

func listEquals(left []int32, right []int32) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] != right[i] {
			return false
		}
	}
	return true
}

${recordDeclarations}

${variantDeclarations}

${functions}

${main}
`;

  return {
    target: "go",
    files: [
      {
        path: "go.mod",
        content: `module hsprogram

go 1.22
`,
      },
      { path: "main.go", content: source },
    ],
    build: ["go", "build", "-o", `bin/${binaryName}`, "."],
    run: [`bin/${binaryName}`],
  };
}

function renderRecords(records: RecordMap, dialect: Dialect, variants: VariantMap): string {
  return [...records.values()]
    .map((record) => {
      const lines = [`type ${record.targetName} struct {`];
      for (const field of record.fields) {
        lines.push(`\t${field.targetName} ${targetType(field.type, records, dialect.intType, dialect.stringType, dialect.listType, variants)}`);
      }
      lines.push("}");
      return lines.join("\n");
    })
    .join("\n\n");
}

function renderVariants(variants: VariantMap, dialect: Dialect): string {
  return [...variants.values()]
    .map((variant) => {
      const lines = [`type ${variant.targetName} struct {`, `\ttag ${dialect.intType}`];
      for (let index = 0; index < variant.maxArity; index++) {
        lines.push(`\tp${index + 1} ${dialect.intType}`);
      }
      lines.push("}");
      return lines.join("\n");
    })
    .join("\n\n");
}

function renderFunction(
  program: TypedProgram,
  signature: FunctionSignature,
  dialect: Dialect,
  records: RecordMap,
  variants: VariantMap,
): string {
  const fn = functionBySignature(program, signature);
  const parameters = fn.params
    .map((param) => `${param.targetName} ${targetType(param.type.name, records, dialect.intType, dialect.stringType, dialect.listType, variants)}`)
    .join(", ");
  const body = emitFunctionBody(fn, dialect, records, variants);
  return `func ${signature.targetName}(${parameters}) Res {\n${indent(body, 1)}\n}`;
}

function renderMain(entry: FunctionSignature): string {
  const params = entry.params;
  const lines: string[] = [];
  lines.push("func badArgs() {");
  lines.push('\tfmt.Println(`{"status":"badargs"}`)');
  lines.push("\tos.Exit(2)");
  lines.push("}");
  lines.push("");
  lines.push("func main() {");
  lines.push(`\tif len(os.Args)-1 != ${params.length} {`);
  lines.push("\t\tbadArgs()");
  lines.push("\t}");
  params.forEach((param, index) => {
    const name = `p${index}`;
    if (param.type === "i32") {
      lines.push(`\t${name}raw, err${index} := strconv.ParseInt(os.Args[${index + 1}], 10, 32)`);
      lines.push(`\tif err${index} != nil {`);
      lines.push("\t\tbadArgs()");
      lines.push("\t}");
      lines.push(`\t${name} := int32(${name}raw)`);
      lines.push(`\t_ = ${name}`);
    } else {
      lines.push(`\tvar ${name} int32`);
      lines.push(`\tswitch os.Args[${index + 1}] {`);
      lines.push('\tcase "true":');
      lines.push(`\t\t${name} = 1`);
      lines.push('\tcase "false":');
      lines.push(`\t\t${name} = 0`);
      lines.push("\tdefault:");
      lines.push("\t\tbadArgs()");
      lines.push("\t}");
    }
  });
  lines.push(
    `\tresult := ${entry.targetName}(${params.map((_, i) => `p${i}`).join(", ")})`,
  );
  lines.push("\tif result.ok {");
  if (entry.returnType === "bool") {
    lines.push('\t\ttext := "false"');
    lines.push("\t\tif result.value != 0 {");
    lines.push('\t\t\ttext = "true"');
    lines.push("\t\t}");
    lines.push(
      '\t\tfmt.Printf("{\\"status\\":\\"ok\\",\\"type\\":\\"bool\\",\\"value\\":%s}\\n", text)',
    );
  } else {
    lines.push(
      '\t\tfmt.Printf("{\\"status\\":\\"ok\\",\\"type\\":\\"i32\\",\\"value\\":%d}\\n", result.value)',
    );
  }
  lines.push("\t} else {");
  lines.push('\t\tcode := "E_OVERFLOW"');
  lines.push(`\t\tif result.code == ${INDEX_FAILURE_CODE} {`);
  lines.push('\t\t\tcode = "E_INDEX"');
  lines.push("\t\t}");
  lines.push(
    '\t\tfmt.Printf("{\\"status\\":\\"error\\",\\"code\\":\\"%s\\",\\"node\\":%d}\\n", code, result.node)',
  );
  lines.push("\t\tos.Exit(1)");
  lines.push("\t}");
  lines.push("}");
  return lines.join("\n");
}

function indent(text: string, tabs: number): string {
  const prefix = "\t".repeat(tabs);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}
