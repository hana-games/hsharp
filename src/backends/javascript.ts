import type { GeneratedProject } from "../contracts/interfaces";
import type { FunctionSignature, TypedProgram } from "../contracts/outcome";
import { INDEX_FAILURE_CODE } from "../contracts/outcome";
import { CORE_VERSION, COMPILER_VERSION } from "../contracts/version";
import {
  collectRecords,
  collectVariants,
  emitFunctionBody,
  functionBySignature,
  planEntryArguments,
  type Dialect,
  type EntryArgumentPlan,
  type RecordMap,
  type VariantMap,
} from "./codegen";

export function emitJavascript(
  program: TypedProgram,
  entryName: string,
  options: { projectName?: string } = {},
): GeneratedProject {
  void options;
  const entry = program.functions.find((fn) => fn.name === entryName);
  if (!entry) throw new Error(`entry function "${entryName}" was not found`);
  const records = collectRecords(program);
  const variants = collectVariants(program);

  const dialect: Dialect = {
    target: "javascript",
    intType: "number",
    stringType: "string",
    intMinLiteral: "-2147483648",
    declare: (name, _type, init) => [`let ${name} = ${init};`],
    declareRes: (name, init) => [`let ${name} = ${init};`],
    assign: (name, expr) => [`${name} = ${expr};`],
    ifOpen: (cond) => `if (${cond}) {`,
    elseIfOpen: (cond) => `} else if (${cond}) {`,
    elseOpen: () => `} else {`,
    closeBlock: () => `}`,
    returnStmt: (expr) => `return ${expr};`,
    resFailed: (expr) => `!${expr}.ok`,
    resValue: (expr) => `${expr}.value`,
    resOk: (expr) => `hsOk(${expr})`,
    resOkRecord: (_record, expr) => `hsOkPayload(${expr})`,
    resRecordValue: (expr, _record) => `${expr}.payload`,
    resOkVariant: (_variant, expr) => `hsOkPayload(${expr})`,
    resVariantValue: (expr, _variant) => `${expr}.payload`,
    resOkString: (expr) => `hsOkPayload(${expr})`,
    resStringValue: (expr) => `${expr}.payload`,
    stringLiteral: (value) => JSON.stringify(value),
    stringValue: (expr) => expr,
    emptyString: () => '""',
    valueEquals: (left, right, _type) => `hsDeepEquals(${left}, ${right})`,
    resFail: (code, node) => `hsFail(${code}, ${node})`,
    checked: (op, args, node) => `hs${op[0].toUpperCase()}${op.slice(1)}(${[...args, String(node)].join(", ")})`,
    call: (fn, args) => `${fn}(${args.join(", ")})`,
    recordLiteral: (record, values) =>
      record.fields.length === 0
        ? "{}"
        : `{ ${record.fields
            .map((field, index) => `${field.targetName}: ${values[index]}`)
            .join(", ")} }`,
    fieldAccess: (target, record, index) => `${target}.${record.fields[index].targetName}`,
    fieldEquals: (left, right, record, index) =>
      `hsDeepEquals(${left}.${record.fields[index].targetName}, ${right}.${record.fields[index].targetName})`,
    constructVariant: (variant, alternative, values) => {
      if (variant.builtin?.kind === "result") {
        const isErr = alternative.payload[0] === "string";
        return `{ tag: ${alternative.tag}, p1: ${isErr ? "0" : values[0] ?? "0"}, s1: ${
          isErr ? values[0] ?? '""' : '""'
        } }`;
      }
      const fields = [
        "tag",
        ...Array.from({ length: variant.maxArity }, (_unused, index) => `p${index + 1}`),
      ];
      const assigned = [
        String(alternative.tag),
        ...values,
        ...Array(Math.max(0, variant.maxArity - values.length)).fill("0"),
      ];
      return `{ ${fields.map((field, index) => `${field}: ${assigned[index]}`).join(", ")} }`;
    },
    variantTag: (expr, _variant) => `${expr}.tag`,
    variantValue: (expr, _variant) => expr,
    variantPayload: (expr, variant, alternative, index) =>
      variant.builtin?.kind === "result" && alternative.payload[0] === "string"
        ? `${expr}.s1`
        : `${expr}.p${index + 1}`,
    variantEquals: (left, right, _variant) => `hsDeepEquals(${left}, ${right})`,
    listType: (_element) => "Array",
    listLiteral: (values) => `[${values.join(", ")}]`,
    emptyList: () => "[]",
    listValue: (expr) => expr,
    listLength: (expr) => `${expr}.length`,
    listIndex: (list, index, node) => `hsIndex(${list}, ${index}, ${node})`,
    listEquals: (left, right, _elementType) => `hsDeepEquals(${left}, ${right})`,
    resOkList: (expr) => `hsOkPayload(${expr})`,
    resListValue: (expr) => `${expr}.payload`,
  };

  const functions = program.functions
    .map((signature) => renderFunction(program, signature, dialect, records, variants))
    .join("\n\n");
  const entryPlan = planEntryArguments(entry, records, dialect, (index) => `p${index}`);
  const main = renderMain(entry, entryPlan);

  const source = `// Generated by h# ${COMPILER_VERSION} (core ${CORE_VERSION}). Do not edit.
"use strict";

${renderHelpers()}

${functions}

${main}
`;

  return {
    target: "javascript",
    files: [
      // Force CommonJS even when an ancestor package.json declares "type":
      // "module"; the generated program uses no modules at all.
      { path: "package.json", content: '{\n  "type": "commonjs"\n}\n' },
      { path: "main.js", content: source },
    ],
    build: ["node", "--check", "main.js"],
    run: ["node", "main.js"],
  };
}

function renderHelpers(): string {
  return `function hsOk(value) {
    return { ok: true, value: value, payload: null, code: 0, node: 0 };
}

function hsOkPayload(payload) {
    return { ok: true, value: 0, payload: payload, code: 0, node: 0 };
}

function hsFail(code, node) {
    return { ok: false, value: 0, payload: null, code: code, node: node };
}

function hsAdd(a, b, node) {
    const r = BigInt(a) + BigInt(b);
    if (r < -2147483648n || r > 2147483647n) return hsFail(1, node);
    return hsOk(Number(r));
}

function hsSub(a, b, node) {
    const r = BigInt(a) - BigInt(b);
    if (r < -2147483648n || r > 2147483647n) return hsFail(1, node);
    return hsOk(Number(r));
}

function hsMul(a, b, node) {
    const r = BigInt(a) * BigInt(b);
    if (r < -2147483648n || r > 2147483647n) return hsFail(1, node);
    return hsOk(Number(r));
}

function hsNeg(a, node) {
    const r = -BigInt(a);
    if (r < -2147483648n || r > 2147483647n) return hsFail(1, node);
    return hsOk(Number(r));
}

function hsIndex(list, index, node) {
    if (index < 0 || index >= list.length) return hsFail(${INDEX_FAILURE_CODE}, node);
    return hsOk(list[index]);
}

function hsDeepEquals(a, b) {
    if (a === b) return true;
    if (Array.isArray(a) || Array.isArray(b)) {
        if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
        for (let i = 0; i < a.length; i++) {
            if (!hsDeepEquals(a[i], b[i])) return false;
        }
        return true;
    }
    if (a !== null && b !== null && typeof a === "object" && typeof b === "object") {
        const aKeys = Object.keys(a);
        const bKeys = Object.keys(b);
        if (aKeys.length !== bKeys.length) return false;
        for (const key of aKeys) {
            if (!Object.prototype.hasOwnProperty.call(b, key)) return false;
            if (!hsDeepEquals(a[key], b[key])) return false;
        }
        return true;
    }
    return false;
}

function hsParseI32(text) {
    if (!/^[+-]?[0-9]+$/.test(text)) return null;
    const value = Number(text);
    if (!Number.isInteger(value) || value < -2147483648 || value > 2147483647) return null;
    return value;
}

function hsParseBool(text) {
    if (text === "true") return 1;
    if (text === "false") return 0;
    return null;
}
`;
}

function renderFunction(
  program: TypedProgram,
  signature: FunctionSignature,
  dialect: Dialect,
  records: RecordMap,
  variants: VariantMap,
): string {
  const fn = functionBySignature(program, signature);
  const parameters = fn.params.map((param) => param.targetName).join(", ");
  const body = emitFunctionBody(fn, dialect, records, variants);
  return `function ${signature.targetName}(${parameters}) {\n${indent(body, 4)}\n}`;
}

function renderMain(entry: FunctionSignature, plan: EntryArgumentPlan): string {
  const leaves = plan.leaves;
  const lines: string[] = [];
  lines.push("function main() {");
  lines.push("    const args = process.argv.slice(2);");
  lines.push(`    if (args.length !== ${leaves.length}) {`);
  lines.push(`        console.log('{"status":"badargs"}');`);
  lines.push("        return 2;");
  lines.push("    }");
  leaves.forEach((leaf, index) => {
    const name = `p${index}`;
    const parser = leaf.type === "i32" ? "hsParseI32" : "hsParseBool";
    lines.push(`    const ${name} = ${parser}(args[${index}]);`);
    lines.push(`    if (${name} === null) {`);
    lines.push(`        console.log('{"status":"badargs"}');`);
    lines.push("        return 2;");
    lines.push("    }");
  });
  lines.push(`    const result = ${entry.targetName}(${plan.args.join(", ")});`);
  lines.push("    if (result.ok) {");
  if (entry.returnType === "bool") {
    lines.push(
      `        console.log('{"status":"ok","type":"bool","value":' + (result.value !== 0 ? "true" : "false") + "}");`,
    );
  } else {
    lines.push(
      `        console.log('{"status":"ok","type":"i32","value":' + result.value + "}");`,
    );
  }
  lines.push("        return 0;");
  lines.push("    }");
  lines.push(
    `    const errorCode = result.code === ${INDEX_FAILURE_CODE} ? "E_INDEX" : "E_OVERFLOW";`,
  );
  lines.push(
    `    console.log('{"status":"error","code":"' + errorCode + '","node":' + result.node + "}");`,
  );
  lines.push("    return 1;");
  lines.push("}");
  lines.push("");
  lines.push("process.exitCode = main();");
  return lines.join("\n");
}

function indent(text: string, spaces: number): string {
  const prefix = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}
