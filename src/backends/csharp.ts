import type { GeneratedProject } from "../contracts/interfaces";
import type { FunctionSignature, TypedProgram } from "../contracts/outcome";
import { INDEX_FAILURE_CODE } from "../contracts/outcome";
import { CORE_VERSION, COMPILER_VERSION } from "../contracts/version";
import {
  collectRecords,
  emitFunctionBody,
  functionBySignature,
  quoteString,
  targetType,
  type Dialect,
  type RecordMap,
} from "./codegen";

export function emitCsharp(
  program: TypedProgram,
  entryName: string,
  options: { projectName?: string } = {},
): GeneratedProject {
  void options;
  const entry = program.functions.find((fn) => fn.name === entryName);
  if (!entry) throw new Error(`entry function "${entryName}" was not found`);
  const records = collectRecords(program);

  const dialect: Dialect = {
    target: "csharp",
    intType: "int",
    stringType: "string",
    intMinLiteral: "int.MinValue",
    declare: (name, type, init) => [`${type} ${name} = ${init};`],
    declareRes: (name, init) => [`Res ${name} = ${init};`],
    assign: (name, expr) => [`${name} = ${expr};`],
    ifOpen: (cond) => `if (${cond}) {`,
    elseOpen: () => `} else {`,
    closeBlock: () => `}`,
    returnStmt: (expr) => `return ${expr};`,
    resFailed: (expr) => `!${expr}.ok`,
    resValue: (expr) => `${expr}.value`,
    resOk: (expr) => `Res.Ok(${expr})`,
    resOkRecord: (_record, expr) => `Res.OkRecord(${expr})`,
    resRecordValue: (expr, record) => `((${record.targetName})${expr}.payload)`,
    resOkString: (expr) => `Res.OkRecord(${expr})`,
    resStringValue: (expr) => `((string)${expr}.payload)`,
    stringLiteral: quoteString,
    stringValue: (expr) => expr,
    valueEquals: (left, right) => `${left} == ${right}`,
    resFail: (code, node) => `Res.Fail(${code}, ${node})`,
    checked: (op, args, node) => `${capitalize(op)}(${[...args, String(node)].join(", ")})`,
    call: (fn, args) => `${fn}(${args.join(", ")})`,
    recordLiteral: (record, values) => `new ${record.targetName}(${values.join(", ")})`,
    fieldAccess: (target, record, index) => `${target}.${record.fields[index].targetName}`,
    fieldEquals: (left, right, record, index) =>
      `${left}.${record.fields[index].targetName} == ${right}.${record.fields[index].targetName}`,
    listType: (element) => `List<${element}>`,
    listLiteral: (values) => `new List<int> { ${values.join(", ")} }`,
    listValue: (expr) => expr,
    listLength: (expr) => `${expr}.Count`,
    listIndex: (list, index, node) => `Index(${list}, ${index}, ${node})`,
    listEquals: (left, right) => `ListEquals(${left}, ${right})`,
    resOkList: (expr) => `Res.OkRecord(${expr})`,
    resListValue: (expr) => `((List<int>)${expr}.payload)`,
  };

  const recordDeclarations = renderRecords(records, dialect);
  const methods = program.functions
    .map((signature) => renderFunction(program, signature, dialect, records))
    .join("\n\n");
  const main = renderMain(entry);
  const source = `// Generated by h# ${COMPILER_VERSION} (core ${CORE_VERSION}). Do not edit.
using System;
using System.Collections.Generic;

internal static class HsProgram
{
    private readonly struct Res
    {
        public readonly bool ok;
        public readonly int value;
        public readonly object payload;
        public readonly int code;
        public readonly int node;

        public Res(bool ok, int value, object payload, int code, int node)
        {
            this.ok = ok;
            this.value = value;
            this.payload = payload;
            this.code = code;
            this.node = node;
        }

        public static Res Ok(int value) => new Res(true, value, null, 0, 0);
        public static Res OkRecord(object payload) => new Res(true, 0, payload, 0, 0);

        public static Res Fail(int code, int node) => new Res(false, 0, null, code, node);
    }

    private static Res Add(int a, int b, int node)
    {
        long r = (long)a + (long)b;
        if (r < -2147483648L || r > 2147483647L) return Res.Fail(1, node);
        return Res.Ok((int)r);
    }

    private static Res Sub(int a, int b, int node)
    {
        long r = (long)a - (long)b;
        if (r < -2147483648L || r > 2147483647L) return Res.Fail(1, node);
        return Res.Ok((int)r);
    }

    private static Res Mul(int a, int b, int node)
    {
        long r = (long)a * (long)b;
        if (r < -2147483648L || r > 2147483647L) return Res.Fail(1, node);
        return Res.Ok((int)r);
    }

    private static Res Neg(int a, int node)
    {
        long r = -(long)a;
        if (r < -2147483648L || r > 2147483647L) return Res.Fail(1, node);
        return Res.Ok((int)r);
    }

    private static Res Index(List<int> list, int index, int node)
    {
        if (index < 0 || index >= list.Count) return Res.Fail(${INDEX_FAILURE_CODE}, node);
        return Res.Ok(list[index]);
    }

    private static bool ListEquals(List<int> left, List<int> right)
    {
        if (left.Count != right.Count) return false;
        for (int i = 0; i < left.Count; i++)
        {
            if (left[i] != right[i]) return false;
        }
        return true;
    }

${recordDeclarations}

${methods}

${main}
}
`;

  return {
    target: "csharp",
    files: [
      {
        path: "HsProgram.csproj",
        content: `<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <AssemblyName>HsProgram</AssemblyName>
    <RootNamespace>HsProgram</RootNamespace>
    <Nullable>disable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <InvariantGlobalization>true</InvariantGlobalization>
  </PropertyGroup>
</Project>
`,
      },
      { path: "Program.cs", content: source },
    ],
    build: ["dotnet", "build", "-c", "Release", "--nologo", "-o", "bin"],
    run: ["dotnet", "bin/HsProgram.dll"],
  };
}

function renderRecords(records: RecordMap, dialect: Dialect): string {
  return [...records.values()]
    .map((record) => {
      const components = record.fields
        .map((field) => `${targetType(field.type, records, dialect.intType, dialect.stringType, dialect.listType)} ${field.targetName}`)
        .join(", ");
      return `    private readonly record struct ${record.targetName}(${components});`;
    })
    .join("\n\n");
}

function renderFunction(
  program: TypedProgram,
  signature: FunctionSignature,
  dialect: Dialect,
  records: RecordMap,
): string {
  const fn = functionBySignature(program, signature);
  const parameters = fn.params
    .map((param) => `${targetType(param.type.name, records, dialect.intType, dialect.stringType, dialect.listType)} ${param.targetName}`)
    .join(", ");
  const body = emitFunctionBody(fn, dialect, records);
  return `    private static Res ${signature.targetName}(${parameters})\n    {\n${indent(body, 8)}\n    }`;
}

function renderMain(entry: FunctionSignature): string {
  const params = entry.params;
  const lines: string[] = [];
  lines.push("    private static int BadArgs()");
  lines.push("    {");
  lines.push('        Console.WriteLine("{\\"status\\":\\"badargs\\"}");');
  lines.push("        return 2;");
  lines.push("    }");
  lines.push("");
  lines.push("    public static int Main(string[] args)");
  lines.push("    {");
  lines.push(`        if (args.Length != ${params.length}) return BadArgs();`);
  params.forEach((param, index) => {
    if (param.type === "i32") {
      lines.push(`        int ${paramName(index)};`);
      lines.push(
        `        if (!int.TryParse(args[${index}], out ${paramName(index)})) return BadArgs();`,
      );
    } else {
      lines.push(`        int ${paramName(index)};`);
      lines.push(`        if (args[${index}] == "true") ${paramName(index)} = 1;`);
      lines.push(`        else if (args[${index}] == "false") ${paramName(index)} = 0;`);
      lines.push(`        else return BadArgs();`);
    }
  });
  lines.push(`        Res result = ${entry.targetName}(${params.map((_, i) => paramName(i)).join(", ")});`);
  lines.push("        if (result.ok)");
  lines.push("        {");
  if (entry.returnType === "bool") {
    lines.push(
      '            Console.WriteLine("{\\"status\\":\\"ok\\",\\"type\\":\\"bool\\",\\"value\\":" + (result.value != 0 ? "true" : "false") + "}");',
    );
  } else {
    lines.push(
      '            Console.WriteLine("{\\"status\\":\\"ok\\",\\"type\\":\\"i32\\",\\"value\\":" + result.value + "}");',
    );
  }
  lines.push("            return 0;");
  lines.push("        }");
  lines.push(
    `        string errorCode = result.code == ${INDEX_FAILURE_CODE} ? "E_INDEX" : "E_OVERFLOW";`,
  );
  lines.push(
    '        Console.WriteLine("{\\"status\\":\\"error\\",\\"code\\":\\"" + errorCode + "\\",\\"node\\":" + result.node + "}");',
  );
  lines.push("        return 1;");
  lines.push("    }");
  return lines.join("\n");
}

function paramName(index: number): string {
  return `p${index}`;
}

function capitalize(text: string): string {
  return text[0].toUpperCase() + text.slice(1);
}

function indent(text: string, spaces: number): string {
  const prefix = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}
