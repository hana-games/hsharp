import { useState, type CSSProperties } from "react";
import type { DemoData, TargetId } from "../data/types";
import { targets as targetMeta } from "../lib/site";
import { useT } from "../i18n/runtime";
import { CodeBlock } from "./CodeBlock";

interface Props {
  demo: DemoData;
}

const facts: Record<TargetId, { value: string; check: string; build: string }> = {
  csharp: { value: "int", check: "long", build: "dotnet" },
  rust: { value: "i32", check: "i64", build: "cargo" },
  go: { value: "int32", check: "int64", build: "go" },
  java: { value: "int", check: "long", build: "javac" },
  cpp: { value: "int32_t", check: "int64_t", build: "g++" },
  javascript: { value: "number", check: "BigInt", build: "node" },
};

export function TargetPrism({ demo }: Props) {
  const t = useT();
  const [targetId, setTargetId] = useState<TargetId>("csharp");
  const [filePath, setFilePath] = useState("Program.cs");

  const target = demo.targets[targetId];
  const meta = targetMeta.find((item) => item.id === targetId) ?? targetMeta[0];
  const activeFile =
    target.files.find((file) => file.path === filePath) ??
    target.files.find((file) => !file.path.endsWith(".csproj") && !file.path.endsWith(".toml") && !file.path.endsWith(".mod") && !file.path.endsWith(".json") && !file.path.endsWith(".gitkeep")) ??
    target.files[0];
  const targetFacts = facts[targetId];

  function selectTarget(id: TargetId) {
    setTargetId(id);
    const next = demo.targets[id];
    const preferred = next.files.find(
      (file) => !file.path.endsWith(".csproj") && !file.path.endsWith(".toml") && !file.path.endsWith(".mod") && !file.path.endsWith(".json") && !file.path.endsWith(".gitkeep"),
    );
    setFilePath(preferred?.path ?? next.files[0]?.path ?? "");
  }

  return (
    <div className="lab target-prism">
      <div className="lab-head">
        <div className="lab-title">{t("Target prism")}</div>
        <span className="index">{t("6 targets · real projects")}</span>
      </div>

      <div className="target-workbench">
        <div className="target-toolbar">
          <div className="target-active">
            <span className="target-active-logo">
              <img src={meta.logo} alt={`${meta.label} logo`} width="22" height="22" />
            </span>
            <span>
              <strong>{meta.label}</strong>
              <small>{t("Real generated project")}</small>
            </span>
          </div>

          <div className="target-selector" role="tablist" aria-label={t("Targets")}>
            {targetMeta.map((item) => (
              <button
                key={item.id}
                type="button"
                role="tab"
                aria-selected={item.id === targetId}
                className={`target-option ${item.id === targetId ? "active" : ""}`}
                style={{ "--target": item.color } as CSSProperties}
                onClick={() => selectTarget(item.id)}
              >
                <img src={item.logo} alt="" width="15" height="15" />
                {item.label}
              </button>
            ))}
          </div>
        </div>

        <div className="target-editor" style={{ "--target": meta.color } as CSSProperties}>
          <div className="target-file-tabs" role="tablist" aria-label={t("Generated files")}>
            {target.files.map((file) => (
              <button
                key={file.path}
                type="button"
                role="tab"
                aria-selected={file.path === activeFile?.path}
                className={`target-file-tab ${file.path === activeFile?.path ? "active" : ""}`}
                onClick={() => setFilePath(file.path)}
              >
                <span className="file-dot" />
                {file.path}
              </button>
            ))}
          </div>

          {activeFile && (
            <CodeBlock
              key={`${targetId}-${activeFile.path}`}
              code={activeFile.content}
              language={targetId}
              showCopy
              className="target-code"
              maxHeight="500px"
            />
          )}
        </div>

        <div className="target-facts">
          <div className="target-fact">
            <span>{t("Value")}</span>
            <code>{targetFacts.value}</code>
          </div>
          <div className="target-fact">
            <span>{t("Checks")}</span>
            <code>{targetFacts.check}</code>
          </div>
          <div className="target-fact">
            <span>{t("Build")}</span>
            <code>{targetFacts.build}</code>
          </div>
          <div className="target-fact">
            <span>{t("Names")}</span>
            <code>fN / vN</code>
          </div>
          <span className="target-generated">
            <span className="status-dot" />
            {t("Generated by h#")}
          </span>
        </div>
      </div>
    </div>
  );
}
